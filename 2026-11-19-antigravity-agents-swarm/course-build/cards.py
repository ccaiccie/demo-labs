def card(name, title, lines, sub=None, size=38):
    im=Image.new("RGB",(1920,1080),(14,17,24)); d=ImageDraw.Draw(im)
    for y in range(1080):
        c=int(14+ (y/1080)*10); d.line([(0,y),(1920,y)],fill=(c,c+3,c+14))
    d.rectangle([0,0,1920,8],fill=(66,133,244))
    d.text((120,110),title,font=font(FB,64),fill=(240,244,255))
    y=230
    if sub: d.text((120,200),sub,font=font(F,34),fill=(150,170,210)); y=290
    for ln in lines:
        if ln.startswith("#"):
            d.text((120,y),ln[1:],font=font(FB,size+4),fill=(120,180,255)); y+=size+26
        else:
            d.text((150,y),ln,font=font(F,size),fill=(220,226,240)); y+=size+20
    d.text((120,1010),"Network Technician  |  learn.techtohire.com  |  quiz.techtohire.com",font=font(F,26),fill=(120,130,160))
    im.save(f"cards/{name}.png")
